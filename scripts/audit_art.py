"""Check asset provenance and every catalog renderer; export honest acceptance evidence."""
from pathlib import Path
import hashlib
import json
import re

root = Path(__file__).resolve().parents[1]
assets = root / 'assets/art'
manifest = json.loads((assets/'manifest.json').read_text())
for name, entry in manifest.items():
    assert hashlib.sha256((assets/name).read_bytes()).hexdigest() == entry['sha256'], name
assert manifest['environment-atlas.png']['frames'] == 56
assert sum(v['frames'] for k,v in manifest.items() if k != 'environment-atlas.png') == 104
entries = re.findall(r'ARCADE_GAME\((\w+),\s*(\w+),\s*(\d+)\)',
                     (root/'include/games/Catalog.def').read_text())
assert len(entries) == 52
lines = ['# Per-game graphics coverage', '',
         'Generated by `python scripts/audit_art.py`. All 52 catalog IDs have renewed graphics.',
         'Each game uses an authored bitmap environment and bitmap actors, objects or puzzle materials.',
         'Shared shooter graphics cover four games with separate scene IDs. River Raid samples its scene',
         'under its real terrain mask rather than replacing the scrolling river with a static picture.', '',
         '| ID | Game | Environment | Foreground bitmap assets | Renderer |',
         '| --- | --- | --- | --- | --- |']
for _, kind, number in entries:
    name = 'ShooterBase' if int(number) < 4 else kind
    source = (root/'src/games'/f'{name}.cpp').read_text()
    if name != 'ShooterBase':
        assert f'art::scene(c, {number}' in source or (kind == 'RiverRaid' and 'art::river(c' in source), kind
    sprites = sorted(set(re.findall(r'art::Sprite::(\w+)', source)))
    if 'visual::tile(' in source or 'art::tile(' in source:
        sprites.append('Block material')
    if 'visual::car(' in source:
        sprites.extend(['Car', 'EnemyCar'])
    if 'ship(c,' in source or 'visual::ship(' in source:
        sprites.append('Jet')
    if kind == 'KeystoneKapers':
        sprites.extend(['Cop / CopStep / CopDuck', 'Thief / ThiefStep'])
    assert sprites, f'No foreground bitmap path for {kind}'
    lines.append(f'| {number} | {kind} | {number} | {", ".join(sorted(set(sprites)))} | [{name}.cpp](../src/games/{name}.cpp) |')
lines += ['', 'Source PNG hashes and packed sizes are in assets/art/manifest.json.',
          'Host simulation and physical device exercises are distinct from manual playability, LCD',
          'legibility, listening tests and every possible gameplay state. See MODERN_GRAPHICS.md.', '']
(root/'docs/GRAPHICS_COVERAGE.md').write_text('\n'.join(lines), encoding='utf-8')
device = root/'artifacts/com9-art-check.log'
if device.exists():
    log = device.read_text(encoding='utf-8', errors='replace')
    rows = re.findall(r'ART_CHECK game=(\d+) heap=(\d+) update=(\d+) draw=(\d+) transfer=(\d+) crc=([0-9a-f]+) stack=(\d+)', log)
    if 'ART_CHECK COMPLETE games=52' in log:
        assert len(rows) == 52 and sorted(int(r[0]) for r in rows) == list(range(52))
        report = [dict(game=int(r[0]), heap_bytes=int(r[1]), update_max_us=int(r[2]),
                       draw_max_us=int(r[3]), transfer_max_us=int(r[4]), framebuffer_crc=r[5],
                       stack_high_water_bytes=int(r[6])) for r in rows]
        (root/'test-results/art-device-results.json').write_text(json.dumps(report,indent=2)+'\n')
        print('Device coverage: 52 complete renderer/update/presentation exercises.')
print('PASS 52 graphics paths; 56 environments; 104 sprites; PNG hashes match provenance.')
