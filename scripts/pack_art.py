"""Pack original generated atlas PNGs into deterministic flash-resident 4-bit artwork.
Requires Pillow 12.3.0. Conversion only: no procedural replacement artwork.
"""
from pathlib import Path
from PIL import Image
import hashlib
import json

root = Path(__file__).resolve().parents[1]
assets = root / "assets/art"

def rgb565(c):
    r, g, b = c
    return ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)

def pack(tile, sprite):
    bounds = None
    if sprite:
        alpha = tile.getchannel("A")
        bounds = alpha.point(lambda p: 255 if p >= 96 else 0).getbbox()
        assert bounds, "Empty sprite cell"
        tile = tile.crop(bounds)
        tile.thumbnail((22, 22), Image.Resampling.LANCZOS)
        canvas = Image.new("RGBA", (24, 24))
        canvas.alpha_composite(tile, ((24-tile.width)//2, (24-tile.height)//2))
        mask = canvas.getchannel("A")
        b = mask.point(lambda p: 255 if p >= 96 else 0).getbbox()
        assert b
        bounds = [b[0], b[1], b[2]-b[0], b[3]-b[1]]
        rgb = canvas.convert("RGB")
        q = rgb.quantize(colors=15, method=Image.Quantize.MEDIANCUT, dither=Image.Dither.NONE)
        values = [v + 1 if a >= 96 else 0 for v, a in zip(q.get_flattened_data(), mask.get_flattened_data())]
        palette = [0] + [rgb565(tuple(q.getpalette()[i:i+3])) for i in range(0, 45, 3)]
    else:
        rgb = tile.convert("RGB").resize((88, 100), Image.Resampling.LANCZOS)
        q = rgb.quantize(colors=16, method=Image.Quantize.MEDIANCUT, dither=Image.Dither.NONE)
        values = list(q.get_flattened_data())
        palette = [rgb565(tuple(q.getpalette()[i:i+3])) for i in range(0, 48, 3)]
    data = [(values[i] << 4) | values[i+1] for i in range(0, len(values), 2)]
    return data, palette, bounds

output = ['// Generated by scripts/pack_art.py. Source PNGs/provenance: assets/art/.',
          '#include "assets/Art.h"', 'namespace arcade { namespace art {']
manifest = {}
for stem, sources in [("scene", [("environment-atlas.png", 8, 7, False)]),
                      ("sprite", [("sprite-atlas.png", 8, 8, True), ("supplement-atlas.png", 8, 4, True),
                                  ("finishing-atlas.png", 4, 2, True)])]:
    data, palettes, bounds = [], [], []
    for file, columns, rows, sprite in sources:
        image = Image.open(assets / file).convert("RGBA")
        # The generated environment sheet has six square rows and a double-height
        # final row. These inspected source boundaries prevent cross-scene bleed.
        row_bounds = [round(r * image.height / rows) for r in range(rows + 1)]
        if file == 'environment-atlas.png':
            assert image.size == (1254, 1254), 'Reinspect environment cell boundaries after replacing its source'
            row_bounds = [0, 157, 313, 470, 627, 784, 940, 1254]
        begin = len(data)
        for row in range(rows):
            for col in range(columns):
                box = (round(col*image.width/columns), row_bounds[row],
                       round((col+1)*image.width/columns), row_bounds[row+1])
                pixels, palette, bound = pack(image.crop(box), sprite)
                data.append(pixels)
                palettes.append(palette)
                bounds.append(bound)
        manifest[file] = dict(sha256=hashlib.sha256((assets/file).read_bytes()).hexdigest(),
                              frames=len(data)-begin, packed_bytes=sum(map(len,data[begin:]))+(len(data)-begin)*32,
                              logical_size=[24,24] if sprite else [88,100], source_row_bounds=row_bounds)
    output.append(f'const uint8_t {stem}Pixels[{len(data)}][{len(data[0])}] = {{')
    for entry in data:
        output.append('{')
        for i in range(0, len(entry), 32):
            output.append(','.join(f'0x{x:02x}' for x in entry[i:i+32])+',')
        output.append('},')
    output.append('};')
    if stem == 'sprite':
        output.append(f'const uint8_t spriteBounds[{len(data)}][4] = {{')
        output.extend('{' + ','.join(map(str, b)) + '},' for b in bounds)
        output.append('};')
    output.append(f'const uint16_t {stem}Colors[{len(data)}][16] = {{')
    output.extend('{' + ','.join(f'0x{x:04x}' for x in palette) + '},' for palette in palettes)
    output.append('};')
output += ['} }', '']
(root/'src/arcade/ArtData.cpp').write_text('\n'.join(output), encoding='utf-8')
(assets/'manifest.json').write_text(json.dumps(manifest,indent=2)+'\n',encoding='utf-8')
print(json.dumps(manifest, indent=2))
